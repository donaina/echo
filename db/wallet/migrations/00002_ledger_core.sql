-- +goose Up
-- Stage 1: accounts, transactions and entries. The ledger's invariants are
-- enforced by the database, not only by the Go code that writes to it.
--
-- There is deliberately no Down migration: dropping a ledger is not a safe
-- operation, and production is forward-only. The tables below are append-only
-- (Article IV), so the recovery plan is a reversal, never a delete.

BEGIN;

CREATE TABLE accounts (
    id           TEXT        PRIMARY KEY,           -- ULID, generated by the service
    tenant_id    TEXT        NOT NULL,              -- ADR 0007: present from day one
    owner_ref    TEXT,                              -- opaque auth reference; NULL for system accounts
    account_type TEXT        NOT NULL,
    currency     TEXT        NOT NULL,
    status       TEXT        NOT NULL DEFAULT 'active',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    version      BIGINT      NOT NULL DEFAULT 1,

    -- A wallet belongs to someone; a system account belongs to no one.
    CONSTRAINT accounts_owner_chk
        CHECK ((account_type = 'wallet') = (owner_ref IS NOT NULL)),
    CONSTRAINT accounts_type_chk
        CHECK (account_type IN ('wallet', 'fee', 'suspense', 'settlement')),
    CONSTRAINT accounts_status_chk
        CHECK (status IN ('active', 'frozen', 'closed')),
    CONSTRAINT accounts_currency_chk
        CHECK (currency ~ '^[A-Z]{3}$'),

    -- Composite keys carry tenant and currency into the entries' foreign keys,
    -- so an entry cannot reference another tenant's or another currency's
    -- account.
    CONSTRAINT accounts_id_tenant_uq UNIQUE (id, tenant_id),
    CONSTRAINT accounts_id_tenant_currency_uq UNIQUE (id, tenant_id, currency)
);

CREATE UNIQUE INDEX accounts_owner_currency_uq
    ON accounts (owner_ref, currency) WHERE account_type = 'wallet';

-- One fee, suspense and settlement account per tenant and currency.
CREATE UNIQUE INDEX accounts_system_uq
    ON accounts (tenant_id, account_type, currency) WHERE account_type <> 'wallet';

CREATE TABLE transactions (
    id             TEXT        PRIMARY KEY,
    tenant_id      TEXT        NOT NULL,
    operation_type TEXT        NOT NULL,
    status         TEXT        NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL,
    value_date     DATE        NOT NULL,
    correlation_id TEXT        NOT NULL,
    causation_id   TEXT,
    created_by     TEXT        NOT NULL,
    reverses_id    TEXT,
    metadata       JSONB       NOT NULL DEFAULT '{}',

    CONSTRAINT transactions_operation_chk CHECK (operation_type IN (
        'fund-wallet', 'withdraw-wallet', 'internal-transfer',
        'fee', 'fx-settlement', 'reversal'
    )),
    CONSTRAINT transactions_status_chk CHECK (status IN ('posted', 'reversed')),

    -- A reversed transaction is the original, and carries no reversal link;
    -- the reversal is a new posted transaction that points at it.
    CONSTRAINT transactions_reversal_chk
        CHECK (status <> 'reversed' OR reverses_id IS NULL),
    CONSTRAINT transactions_reversal_posted_chk
        CHECK (reverses_id IS NULL OR status = 'posted'),

    CONSTRAINT transactions_id_tenant_uq UNIQUE (id, tenant_id),
    CONSTRAINT transactions_reverses_fk
        FOREIGN KEY (reverses_id, tenant_id) REFERENCES transactions (id, tenant_id)
);

-- A transaction is reversed at most once.
CREATE UNIQUE INDEX transactions_reverses_uq
    ON transactions (reverses_id) WHERE reverses_id IS NOT NULL;

CREATE INDEX transactions_tenant_time_idx ON transactions (tenant_id, occurred_at, id);

CREATE TABLE entries (
    id             TEXT        PRIMARY KEY,
    tenant_id      TEXT        NOT NULL,
    transaction_id TEXT        NOT NULL,
    account_id     TEXT        NOT NULL,
    delta_minor    BIGINT      NOT NULL,  -- signed change to the account's ledger balance
    currency       TEXT        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT entries_nonzero_chk CHECK (delta_minor <> 0),
    CONSTRAINT entries_transaction_fk
        FOREIGN KEY (transaction_id, tenant_id) REFERENCES transactions (id, tenant_id),
    CONSTRAINT entries_account_fk
        FOREIGN KEY (account_id, tenant_id, currency)
        REFERENCES accounts (id, tenant_id, currency)
);

CREATE INDEX entries_account_created_idx ON entries (account_id, created_at, id);
CREATE INDEX entries_transaction_idx ON entries (transaction_id);

-- Article III, enforced at commit: the entries of a transaction sum to zero in
-- each currency they touch, and a transaction never mixes currencies.
-- +goose StatementBegin
CREATE FUNCTION check_transaction_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    tx_id TEXT;
BEGIN
    IF TG_TABLE_NAME = 'transactions' THEN
        tx_id := NEW.id;
    ELSE
        tx_id := NEW.transaction_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM entries WHERE transaction_id = tx_id) THEN
        RAISE EXCEPTION 'transaction % has no entries', tx_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF (SELECT count(DISTINCT currency) FROM entries WHERE transaction_id = tx_id) > 1 THEN
        RAISE EXCEPTION 'transaction % mixes currencies', tx_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF EXISTS (
        SELECT 1 FROM entries
        WHERE transaction_id = tx_id
        GROUP BY currency
        HAVING sum(delta_minor) <> 0
    ) THEN
        RAISE EXCEPTION 'transaction % is not balanced', tx_id
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$;
-- +goose StatementEnd

CREATE CONSTRAINT TRIGGER transactions_balanced
    AFTER INSERT ON transactions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_transaction_balanced();

CREATE CONSTRAINT TRIGGER entries_balanced
    AFTER INSERT ON entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_transaction_balanced();

-- Article IV: an entry is never updated or deleted.
-- +goose StatementBegin
CREATE FUNCTION forbid_entry_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'entries are append-only: post a reversing transaction instead'
        USING ERRCODE = 'restrict_violation';
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER entries_append_only
    BEFORE UPDATE OR DELETE ON entries
    FOR EACH ROW EXECUTE FUNCTION forbid_entry_changes();

-- A transaction may change only its status, and only once, from posted to
-- reversed. Every other column and every delete is refused.
-- +goose StatementBegin
CREATE FUNCTION check_transaction_immutability() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'transactions are never deleted'
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
        OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
        OR NEW.operation_type IS DISTINCT FROM OLD.operation_type
        OR NEW.occurred_at IS DISTINCT FROM OLD.occurred_at
        OR NEW.value_date IS DISTINCT FROM OLD.value_date
        OR NEW.correlation_id IS DISTINCT FROM OLD.correlation_id
        OR NEW.causation_id IS DISTINCT FROM OLD.causation_id
        OR NEW.created_by IS DISTINCT FROM OLD.created_by
        OR NEW.reverses_id IS DISTINCT FROM OLD.reverses_id
        OR NEW.metadata IS DISTINCT FROM OLD.metadata
    THEN
        RAISE EXCEPTION 'only transactions.status may change'
            USING ERRCODE = 'restrict_violation';
    END IF;

    IF OLD.status <> 'posted' OR NEW.status <> 'reversed' THEN
        RAISE EXCEPTION 'transactions.status moves only from posted to reversed'
            USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER transactions_immutable
    BEFORE UPDATE OR DELETE ON transactions
    FOR EACH ROW EXECUTE FUNCTION check_transaction_immutability();

-- A transaction may be marked reversed only by a transaction that actually
-- reverses it. Deferred, because the reversal row and the status change are
-- written in the same transaction and become visible together.
-- +goose StatementBegin
CREATE FUNCTION check_reversal_exists() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM transactions WHERE reverses_id = NEW.id) THEN
        RAISE EXCEPTION 'transaction % is marked reversed without a reversal', NEW.id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$;
-- +goose StatementEnd

CREATE CONSTRAINT TRIGGER transactions_reversal_exists
    AFTER UPDATE OF status ON transactions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.status = 'reversed')
    EXECUTE FUNCTION check_reversal_exists();

-- Article IV at the privilege layer too, where the deployment role exists.
-- The triggers above are the guard that also covers a role the migration
-- cannot see, such as the test container's superuser.
-- +goose StatementBegin
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'echo_wallet_app') THEN
        REVOKE UPDATE, DELETE ON entries FROM echo_wallet_app;
        REVOKE DELETE ON transactions FROM echo_wallet_app;
    END IF;
END;
$$;
-- +goose StatementEnd

